/// Memoization key for [CodeHighlighter.highlight].
class _CacheKey {
  const _CacheKey(this.language, this.code, this.theme, this.enabled);

  final String language;
  final String code;
  final CodeBlockTheme theme;
  final bool enabled;

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      other is _CacheKey &&
          other.language == language &&
          other.code == code &&
          other.theme == theme &&
          other.enabled == enabled;

  @override
  int get hashCode => Object.hash(language, code, theme, enabled);
}
