/// Token kinds emitted by [CodeHighlighter].
enum _TokenKind {
  comment,
  string,
  number,
  keyword,
  type,
  function,
  annotation,
  punctuation,
  plain,
}

/// A pure-Dart regex-based syntax highlighter that produces a [TextSpan]
/// tree styled by a [CodeBlockTheme].
///
/// No span ever sets `backgroundColor` — backgrounds belong to the
/// container, so selections and parent decorations stay intact.
///
/// Results are memoized in a bounded LRU cache (~64 entries) keyed by
/// (language, code, theme, enabled), so repeated identical calls return
/// the cached span without re-tokenizing.
class CodeHighlighter {
  const CodeHighlighter();

  /// Number of times real tokenization ran. Cache hits and disabled /
  /// empty inputs do not increment this.
  @visibleForTesting
  static int debugHighlightCount = 0;

  static const int _cacheLimit = 64;

  static final LinkedHashMap<_CacheKey, TextSpan> _cache =
      LinkedHashMap<_CacheKey, TextSpan>();

  /// Clears the memoization cache and resets [debugHighlightCount].
  @visibleForTesting
  static void debugClearCache() {
    _cache.clear();
    debugHighlightCount = 0;
  }

  /// Highlights [code] for [language] using [theme].
  ///
  /// When [enabled] is false — or [code] is empty — returns a single
  /// plain span in `theme.baseStyle`. Unknown or null languages use a
  /// generic fallback tokenizer; this method never throws on input shape.
  TextSpan highlight(
    String code, {
    String? language,
    required CodeBlockTheme theme,
    bool enabled = true,
  }) {
    if (!enabled || code.isEmpty) {
      return TextSpan(text: code, style: theme.baseStyle);
    }
    final key = _CacheKey(_normalize(language), code, theme, enabled);
    final cached = _cache.remove(key);
    if (cached != null) {
      _cache[key] = cached; // reinsert at the end → most-recently-used
      return cached;
    }
    debugHighlightCount++;
    final span = _tokenize(code, _specFor(key.language), theme);
    _cache[key] = span;
    if (_cache.length > _cacheLimit) {
      _cache.remove(_cache.keys.first);
    }
    return span;
  }

  // ---------------------------------------------------------------------
  // Tokenizer
  // ---------------------------------------------------------------------

  TextSpan _tokenize(String code, _LangSpec spec, CodeBlockTheme theme) {
    final spans = <TextSpan>[];
    var index = 0;
    for (final match in spec.pattern.allMatches(code)) {
      if (match.start > index) {
        spans.add(
          TextSpan(
            text: code.substring(index, match.start),
            style: theme.baseStyle,
          ),
        );
      }
      final kind = _classify(match, code, spec);
      spans.add(TextSpan(text: match.group(0), style: _styleFor(kind, theme)));
      index = match.end;
    }
    if (index < code.length) {
      spans.add(TextSpan(text: code.substring(index), style: theme.baseStyle));
    }
    return TextSpan(style: theme.baseStyle, children: spans);
  }

  _TokenKind _classify(RegExpMatch match, String code, _LangSpec spec) {
    if (match.namedGroup('comment') != null) return _TokenKind.comment;
    if (match.namedGroup('string') != null) return _TokenKind.string;
    if (match.namedGroup('number') != null) return _TokenKind.number;
    if (match.namedGroup('annotation') != null) return _TokenKind.annotation;
    if (match.namedGroup('tag') != null) return _TokenKind.keyword;
    if (match.namedGroup('punct') != null) return _TokenKind.punctuation;
    final ident = match.namedGroup('ident');
    if (ident != null) {
      final lookup = spec.caseInsensitiveKeywords ? ident.toLowerCase() : ident;
      if (spec.keywords.contains(lookup)) return _TokenKind.keyword;
      if (spec.builtins.contains(ident)) return _TokenKind.type;
      final first = ident.codeUnitAt(0);
      if (first >= 0x41 && first <= 0x5A) return _TokenKind.type; // A-Z
      if (match.end < code.length && code[match.end] == '(') {
        return _TokenKind.function;
      }
    }
    return _TokenKind.plain;
  }

  TextStyle _styleFor(_TokenKind kind, CodeBlockTheme theme) {
    switch (kind) {
      case _TokenKind.comment:
        return theme.baseStyle.copyWith(color: theme.commentColor);
      case _TokenKind.string:
        return theme.baseStyle.copyWith(color: theme.stringColor);
      case _TokenKind.number:
        return theme.baseStyle.copyWith(color: theme.numberColor);
      case _TokenKind.keyword:
        return theme.baseStyle.copyWith(color: theme.keywordColor);
      case _TokenKind.type:
        return theme.baseStyle.copyWith(color: theme.typeColor);
      case _TokenKind.function:
        return theme.baseStyle.copyWith(color: theme.functionColor);
      case _TokenKind.annotation:
        return theme.baseStyle.copyWith(color: theme.annotationColor);
      case _TokenKind.punctuation:
        return theme.baseStyle.copyWith(color: theme.punctuationColor);
      case _TokenKind.plain:
        return theme.baseStyle;
    }
  }

